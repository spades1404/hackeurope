// Helper functions
export const formatCurrency = (amount, currency = 'USD') => {
  const symbol = {
    USD: '$',
    GBP: '£',
    EUR: '€',
    AUD: 'A$',
  }[currency] || '$';

  const formatted = Math.abs(amount).toLocaleString('en-US', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  });

  return `${symbol}${formatted}`;
};

